function waitForPrimaryHello(timeoutMs = 15000): Promise<boolean> {
  return new Promise((resolve) => {
    const timer = setTimeout(() => {
      off();
      resolve(false);
    }, timeoutMs);
    const off = bus.on('preview-hello', ({ instanceId }) => {
      if (studio().instances[instanceId]?.role !== 'primary') return;
      clearTimeout(timer);
      off();
      // Let wire.ts finish restoring overrides and the DOM snapshot.
      setTimeout(() => resolve(true), 350);
    });
  });
}

const RELATED: Record<string, string[]> = {
  gap: ['row-gap', 'column-gap'],
  inset: ['top', 'right', 'bottom', 'left'],
  'border-radius': ['border-top-left-radius', 'border-top-right-radius', 'border-bottom-right-radius', 'border-bottom-left-radius'],
  'border-color': ['border-top-color', 'border-right-color', 'border-bottom-color', 'border-left-color'],
  'border-width': ['border-top-width', 'border-right-width', 'border-bottom-width', 'border-left-width'],
  overflow: ['overflow-x', 'overflow-y'],
  'place-items': ['align-items', 'justify-items'],
  font: ['font-family', 'font-size', 'font-weight', 'line-height', 'font-style'],
};

function relevantValues(computed: Record<string, string> | null, prop: string): string | null {
  if (!computed) return null;
  if (prop in computed) return computed[prop];
  const keys = RELATED[prop] ?? Object.keys(computed).filter((k) => k.startsWith(`${prop}-`));
  if (!keys.length) return null;
  return keys.map((k) => `${k}:${computed[k] ?? ''}`).join(';');
}

type Probe = { id: string; selector: string; property: string; expected: string | null };

async function measure(probes: Probe[]): Promise<Map<string, string | null>> {
  const conn = previews.primary();
  const out = new Map<string, string | null>();
  if (!conn?.ready) return out;
  const cache = new Map<string, Record<string, string> | null>();
  for (const p of probes) {
    if (!cache.has(p.selector)) {
      const id = await conn.call('dom.resolve', { selector: p.selector }).catch(() => null);
      cache.set(p.selector, id ? await conn.call('node.computed', { id }).catch(() => null) : null);
    }
    out.set(p.id, relevantValues(cache.get(p.selector) ?? null, p.property));
  }
  return out;
}

function probesFor(changes: Change[]): Probe[] {
  const out: Probe[] = [];
  for (const c of changes) {
    if (c.kind === 'style') out.push({ id: c.id, selector: c.target.selector, property: c.property, expected: null });
    else if (c.kind === 'visibility') out.push({ id: c.id, selector: c.target.selector, property: 'display', expected: null });
    else if (c.kind === 'rule') out.push({ id: c.id, selector: c.target.selector, property: c.property, expected: null });
    else if (c.kind === 'token') out.push({ id: c.id, selector: 'html', property: c.property, expected: null });
  }
  return out;
}

export type ApplyResult = { written: string[]; verified: string[]; kept: string[]; unverifiable: string[] };

/**
 * Write the patch into the project, reload the preview and keep only the
 * overrides the source does not reproduce yet. Text/attribute edits are
 * verified by comparing the rendered text / attributes.
 */
export async function applyPatchToProject(patch: SourcePatch, opts: { onStatus?: (s: string) => void } = {}): Promise<ApplyResult | null> {
  const s = studio();
  const source = s.source;
  const access = sourceAccess(source);
  if (!source || access.kind === 'none' || access.kind === 'demo') throw new Error(access.reason ?? 'This project cannot be written.');
  const ids = new Set(patch.mappedChangeIds);
  const applied = s.changes.filter((c) => ids.has(c.id));
  const probes = probesFor(applied);

  // 1. Expected rendering with overrides active.
  opts.onStatus?.('Measuring the current preview…');
  const expected = await measure(probes);

  // 2. Write.
  const files = patch.files.map((f) => ({ path: f.path, before: f.isNew ? null : f.before, after: f.after, patch: f }));
  if (source.kind === 'vfs') {
    opts.onStatus?.(`Saving ${files.length} file(s)…`);
    await saveVfsFiles(source.projectId, files.map((f) => ({ path: f.path, text: f.after })));
  } else if (source.kind === 'fs') {
    const withHashes = await Promise.all(files.map(async (f) => ({ ...f, baseSha256: f.before === null ? undefined : await sourceHash(source, f.path) })));
    const ok = await approveFsWrite(source.rootId, withHashes, { title: `Apply IFDY changes to ${files.length} file${files.length === 1 ? '' : 's'}`, reason: 'export.apply' });
    if (!ok) return null;
    const { invalidateSources } = await import('@/modules/code-editor/sources');
    invalidateSources();
  }

  // 3. Reload and compare without the applied overrides.
  opts.onStatus?.('Reloading the preview from source…');
  const hello = waitForPrimaryHello();
  studio().reloadPreview();
  const loaded = await hello;
  const verified: string[] = [];
  const kept: string[] = [];
  const unverifiable: string[] = [];
  if (loaded) {
    const conn = previews.primary();
    const remaining = studio().changes.filter((c) => !ids.has(c.id));
    opts.onStatus?.('Verifying the source reproduces your edits…');
    if (conn?.ready) await conn.call('patch.apply', buildPatchSet(remaining, studio().tokens, false)).catch(() => null);
    await new Promise((r) => setTimeout(r, 120));
    const actual = await measure(probes);
    for (const c of applied) {
      const p = probes.find((x) => x.id === c.id);
      if (!p) {
        // Text / attribute edits: the patch either replaced the original or not; check by re-reading the element.
        if (c.kind === 'text' || c.kind === 'attribute') {
          const id = conn?.ready ? await conn.call('dom.resolve', { selector: c.target.selector }).catch(() => null) : null;
          const info = id && conn ? await conn.call('node.info', { id }).catch(() => null) : null;
          const ok = c.kind === 'text' ? info?.text?.replace(/\s+/g, ' ').trim() === (c.after ?? '').replace(/\s+/g, ' ').trim() : info?.attrs.find(([n]) => n === c.property)?.[1] === (c.after ?? undefined);
          (ok ? verified : kept).push(c.id);
        } else unverifiable.push(c.id);
        continue;
      }
      const want = expected.get(c.id);
      const got = actual.get(c.id);
      if (want === undefined || want === null || got === undefined || got === null) unverifiable.push(c.id);
      else if (want === got) verified.push(c.id);
      else kept.push(c.id);
    }
    // Restore whatever should stay live.
    if (conn?.ready) conn.tell('patch.apply', currentPatchSet());
  } else {
    unverifiable.push(...applied.map((c) => c.id));
  }

  // 4. Update the change list: verified edits are committed and leave the live override list.
  const st = studio();
  if (verified.length) {
    st.setExportStatus(verified, 'committed');
    const after = studio();
    const left = after.changes.filter((c) => !verified.includes(c.id));
    useStudio.setState({ ...replaceAll({ changes: after.changes, undoStack: after.undoStack, redoStack: after.redoStack }, left), saveStatus: 'unsaved' });
  }
  const stillPending = [...kept, ...unverifiable];
  if (stillPending.length) studio().setExportStatus(stillPending, 'exported');
  recordExport({ kind: 'apply', label: `Applied to ${source.kind === 'vfs' ? 'project files' : 'local files'}`, detail: `${verified.length} verified · ${kept.length} kept live · ${unverifiable.length} not verifiable`, changeCount: applied.length, files: files.map((f) => f.path) });
  return { written: files.map((f) => f.path), verified, kept, unverifiable };
}
