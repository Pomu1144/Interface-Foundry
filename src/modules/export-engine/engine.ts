export function exportableChanges(changes: Change[], includeExperiments: boolean): Change[] {
  return effectiveChanges(changes).filter((c) => !isNoop(c) && c.exportStatus !== 'committed' && (includeExperiments || !c.experiment));
}

/** Live value of every token (committed token edits applied). */
export function liveTokenValues(changes: Change[]): Record<string, string> {
  const out: Record<string, string> = {};
  for (const c of effectiveChanges(changes)) if (c.kind === 'token' && c.after !== null) out[c.property] = c.after;
  return out;
}

export function overrideCssText(changes: Change[], includeExperiments = false): string {
  const list = exportableChanges(changes, includeExperiments);
  const tokens = liveTokenValues(list);
  const tokenCss = Object.keys(tokens).length ? `:root {\n${Object.entries(tokens).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}\n\n` : '';
  const ruleAsStyle = list
    .filter((c) => c.kind === 'rule' && c.after !== null)
    .map((c) => ({ ...c, kind: 'style' as const, target: { ...c.target, selector: c.target.ruleSelector ?? c.target.selector }, media: c.target.ruleMedia?.filter((m) => !m.startsWith('@container')).join(' and ') || undefined }));
  const body = buildOverrideCss([...list.filter((c) => c.kind === 'style' || c.kind === 'visibility'), ...ruleAsStyle], false);
  const css = tokenCss + body;
  return css.trim() ? `/* ifdy-overrides.css — generated by IFDY (Interface Foundry) */\n\n${css}\n` : '';
}

