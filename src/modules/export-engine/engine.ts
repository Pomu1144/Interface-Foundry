export function downloadBlob(name: string, blob: Blob) {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = name;
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
}

export function downloadText(name: string, text: string, mime = 'text/plain') {
  downloadBlob(name, new Blob([text], { type: `${mime};charset=utf-8` }));
}

export const slugify = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 48) || 'export';

function dataUrlBytes(dataUrl: string): Uint8Array {
  const [, b64 = ''] = dataUrl.split(',');
  const bin = atob(b64);
  const out = new Uint8Array(bin.length);
  for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
  return out;
}

export function screenshotsZip(captures: CaptureRef[]): Uint8Array {
  const files: Record<string, Uint8Array> = {};
  const used = new Set<string>();
  const manifest = captures.map((c) => {
    const ext = /^data:image\/(png|jpeg|webp)/.exec(c.dataUrl)?.[1]?.replace('jpeg', 'jpg') ?? 'png';
    let name = `${slugify(c.label || 'capture')}-${slugify(c.viewport.deviceName)}-${c.viewport.width}x${c.viewport.height}`;
    while (used.has(name)) name += '-2';
    used.add(name);
    files[`screenshots/${name}.${ext}`] = dataUrlBytes(c.dataUrl);
    return { file: `screenshots/${name}.${ext}`, label: c.label, kind: c.kind, route: c.route, device: c.viewport.deviceName, posture: c.viewport.posture, orientation: c.viewport.orientation, width: c.width, height: c.height, viewport: `${c.viewport.width}×${c.viewport.height}`, createdAt: new Date(c.createdAt).toISOString(), changeCount: c.changeCount };
  });
  files['manifest.json'] = strToU8(JSON.stringify({ generator: 'IFDY (Interface Foundry)', exportedAt: new Date().toISOString(), note: 'kind "raster" = DOM raster (approximate); "chromium" = controlled-browser screenshot', captures: manifest }, null, 2));
  return zipSync(files, { level: 0 });
}

export function changeSummaryDocument(projectName: string, changes: Change[], patch: SourcePatch | null): string {
  const list = exportableChanges(changes, true);
  const lines = [
    `# Change summary — ${projectName}`,
    '',
    `Generated by IFDY on ${new Date().toLocaleString()}. ${list.length} effective change${list.length === 1 ? '' : 's'}${list.some((c) => c.experiment) ? ' (🧪 = experiment, not exported by default)' : ''}.`,
    '',
    '## Changes',
    '',
    changeSummaryMarkdown(list),
  ];
  if (patch) {
    lines.push('', '## Source mapping', '', `| | Count |`, `|---|---|`, `| Exact (rule/token/text matched) | ${patch.stats.exact} |`, `| Appended (new rule / override) | ${patch.stats.appended} |`, `| Needs review | ${patch.stats.review} |`, `| Not mapped | ${patch.stats.unmapped} |`);
    if (patch.files.length) lines.push('', '### Files', '', ...patch.files.map((f) => `- \`${f.path}\` (+${f.additions} −${f.deletions})${f.isNew ? ' — new file' : ''}`));
    if (patch.unmapped.length) lines.push('', '### Not mapped', '', ...patch.unmapped.map((u) => `- ${u.label}: ${u.reason}`));
  }
  return lines.join('\n') + '\n';
}

