export type HistoryKind = 'css' | 'copy' | 'patch' | 'tokens' | 'zip' | 'markdown' | 'report' | 'apply' | 'git';
export type HistoryEntry = { id: string; at: number; kind: HistoryKind; label: string; detail?: string; changeCount: number; files?: string[] };

const HISTORY_CAP = 60;
const historyKey = () => `ifdy.export.history.${studio().project?.id ?? 'none'}`;
const historyListeners = new Set<() => void>();
let historyCache: { key: string; list: HistoryEntry[] } | null = null;

export function readHistory(): HistoryEntry[] {
  const key = historyKey();
  if (historyCache?.key === key) return historyCache.list;
  let list: HistoryEntry[] = [];
  try {
    list = JSON.parse(localStorage.getItem(key) ?? '[]') as HistoryEntry[];
  } catch {
    list = [];
  }
  historyCache = { key, list };
  return list;
}

export function recordExport(e: Omit<HistoryEntry, 'id' | 'at'>) {
  const list = [{ ...e, id: `x${Date.now().toString(36)}${Math.random().toString(36).slice(2, 5)}`, at: Date.now() }, ...readHistory()].slice(0, HISTORY_CAP);
  try {
    localStorage.setItem(historyKey(), JSON.stringify(list));
  } catch {
    /* storage full */
  }
  historyCache = { key: historyKey(), list };
  historyListeners.forEach((l) => l());
}

export function clearHistory() {
  try {
    localStorage.removeItem(historyKey());
  } catch {
    /* ignore */
  }
  historyCache = null;
  historyListeners.forEach((l) => l());
}

export function useExportHistory(): HistoryEntry[] {
  useStudio((st) => st.project?.id);
  return useSyncExternalStore(
    (fn) => {
      historyListeners.add(fn);
      return () => historyListeners.delete(fn);
    },
    readHistory,
  );
}

