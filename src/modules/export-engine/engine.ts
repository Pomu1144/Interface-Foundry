export type PatchState = { status: 'idle' | 'loading' | 'ready' | 'error'; patch: SourcePatch | null; error?: string; sourceFiles: number };

export function useSourcePatch(includeExperiments: boolean): PatchState {
  const source = useStudio((st) => st.source);
  const changes = useStudio((st) => st.changes);
  const ver = useSyncExternalStore(onSourcesChanged, sourcesVersion);
  const [files, setFiles] = useState<{ key: string; files: Awaited<ReturnType<typeof loadTextSources>>; error?: string } | null>(null);
  const needsScripts = changes.some((c) => c.kind === 'text' || c.kind === 'attribute');
  const key = `${sourceKey(source)}|${ver}|${needsScripts}`;
  useEffect(() => {
    let cancelled = false;
    if (files?.key === key) return;
    loadTextSources(source, { scripts: needsScripts })
      .then((f) => !cancelled && setFiles({ key, files: f }))
      .catch((err) => !cancelled && setFiles({ key, files: null, error: err instanceof Error ? err.message : String(err) }));
    return () => {
      cancelled = true;
    };
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [key]);
  const entry = source && source.kind !== 'url' && source.kind !== 'proxy' ? source.entry.replace(/#.*$/, '') : undefined;
  return useMemo<PatchState>(() => {
    if (!files || files.key !== key) return { status: 'loading', patch: null, sourceFiles: 0 };
    if (files.error) return { status: 'error', patch: null, error: files.error, sourceFiles: 0 };
    try {
      const patch = buildSourcePatch({ changes, files: files.files, entry, includeExperiments });
      return { status: 'ready', patch, sourceFiles: files.files?.length ?? 0 };
    } catch (err) {
      return { status: 'error', patch: null, error: err instanceof Error ? err.message : String(err), sourceFiles: 0 };
    }
  }, [files, key, changes, entry, includeExperiments]);
}

